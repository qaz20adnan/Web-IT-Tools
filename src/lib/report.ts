const bullets = (items: string[]) => (items.length ? items.map((item) => `- ${item}`).join('\n') : '—')

const stepSection = (steps: AnalysisResult['diagnosticSteps']) =>
  steps.length
    ? steps
        .map((step) => {
          const lines = [`${step.order}. **${step.title}** _(${step.kind}, risk: ${step.risk})_`, `   ${step.detail}`]
          if (step.command) lines.push('', '   ```', `   ${step.command.replaceAll('\n', '\n   ')}`, '   ```')
          if (step.rollback) lines.push('', `   Rollback: ${step.rollback}`)
          return lines.join('\n')
        })
        .join('\n\n')
    : '—'

export function buildReportMarkdown(result: AnalysisResult, input: ProblemInput | undefined, lang: Language): string {
  const l = lang === 'ar' ? AR : EN
  const lines: string[] = [
    `# ${l.title}`,
    '',
    `> ${result.offline ? l.offline : `${l.generatedBy}: ${result.provider} (${result.model})`}`,
    '',
    `- ${l.problem}: ${input?.title || result.summary.slice(0, 120)}`,
    `- ${l.category}: ${result.category}`,
    `- ${l.priority}: ${input?.priority ?? '—'}`,
    `- ${l.environment}: ${input?.environment || '—'}`,
    `- ${l.generated}: ${result.generatedAt}`,
    `- ${l.confidence}: ${result.confidence.level} — ${result.confidence.reason}`,
    '',
    `## ${l.summary}`,
    result.summary,
    '',
    `## ${l.symptoms}`,
    bullets(result.symptoms),
    '',
    `## ${l.causes}`,
    result.causes.length
      ? result.causes
          .map(
            (cause) =>
              `### ${cause.cause} (likelihood: ${cause.likelihood})\n${bullets(cause.evidence)}`,
          )
          .join('\n\n')
      : '—',
    '',
    `## ${l.evidence}`,
    result.evidence.length
      ? result.evidence.map((item) => `- [${item.type}] ${item.statement}`).join('\n')
      : '—',
    '',
    `## ${l.diagnostics}`,
    stepSection(result.diagnosticSteps),
    '',
    `## ${l.solutions}`,
    stepSection(result.solutions),
    '',
    `## ${l.prerequisites}`,
    bullets(result.prerequisites),
    '',
    `## ${l.risks}`,
    bullets(result.risks),
    '',
    `## ${l.rollback}`,
    result.rollback || '—',
    '',
    `## ${l.missing}`,
    bullets(result.missingInformation),
    '',
    `## ${l.limitations}`,
    result.limitations,
    '',
    `## ${l.sources}`,
    result.sources.length
      ? result.sources.map((source) => `- [${source.title}](${source.url})`).join('\n')
      : '—',
    '',
  ]
  return lines.join('\n')
}

export function reportFilename(title: string): string {
  const slug = title
    .toLowerCase()
    .replace(/[^a-z0-9\u0600-\u06FF]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60)
  return `adnan-tech-report-${slug || 'analysis'}.md`
}
