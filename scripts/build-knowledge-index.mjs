import { build } from 'esbuild'
import { mkdtempSync, statSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'

/**
 * The knowledge catalog is one module holding both the metadata every list
 * surface needs (45 titles, summaries, tags, dates) and the full article bodies,
 * which exactly one route reads: ArticlePage. Because a bundler cannot split an
 * object literal, importing the catalog for a title pulled all 250 kB of prose
 * into the entry chunk — the shell, the dashboard and the command palette paid
 * for every article on first paint.
 *
 * This writes src/data/knowledgeMeta.ts: the same array with `body` removed. It
 * is committed so `npm run dev`, `tsc` and `vitest` work without a build step,
 * and tests/knowledge-meta.test.ts compares it against the catalog field by
 * field, so a new article with no regenerated index fails the suite instead of
 * quietly disappearing from search.
 */
const TARGET = 'src/data/knowledgeMeta.ts'

const tmp = join(mkdtempSync(join(tmpdir(), 'nexora-knowledge-index-')), 'catalog.mjs')
const result = await build({
  absWorkingDir: process.cwd(),
  alias: { '@': './src' },
  bundle: true,
  entryPoints: ['src/data/knowledge.ts'],
  external: ['node:*'],
  format: 'esm',
  outfile: tmp,
  platform: 'node',
  target: 'node22',
})
if (result.errors.length > 0) process.exit(1)

const { KNOWLEDGE_ARTICLES } = await import(pathToFileURL(tmp).href)
const articles = KNOWLEDGE_ARTICLES.map(({ body, ...meta }) => meta)

const header = `// GENERATED by scripts/build-knowledge-index.mjs — do not edit by hand.
// Regenerate with \`npm run build:knowledge-index\` (also part of \`npm run build\`).
// This is src/data/knowledge.ts with the article \`body\` field removed: the list
// surfaces and the command palette need titles, summaries and tags, not the full
// article bodies, and importing the catalog for a metadata field is what pinned
// the whole library to the entry chunk. tests/knowledge-meta.test.ts fails if
// this file and the catalog drift apart.

import type { KnowledgeArticle } from '@/types'

export type KnowledgeArticleMeta = Omit<KnowledgeArticle, 'body'>

export const KNOWLEDGE_META: KnowledgeArticleMeta[] = `

writeFileSync(TARGET, `${header}${JSON.stringify(articles, null, 2)}\n`, 'utf8')
const bytes = statSync(TARGET).size
console.log(`${TARGET} ready (${articles.length} articles, ${Math.round(bytes / 1024)} kB)`)
